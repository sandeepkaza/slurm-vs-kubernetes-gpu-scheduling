"""Paper 6 job-trace generator.

Emits one JSON trace replayed identically against Slurm and Kubernetes.
Poisson arrivals, mixed GPU widths and priorities. Seeded, so the same trace
file is regenerated byte-for-byte on any host.

Usage:
  python trace_gen.py --jobs 60 --gpus 2 --rate 0.25 --seed 20260723 -o trace.json
"""

import argparse
import json
import random


def gen(n_jobs, n_gpus, rate, seed, burn_lo, burn_hi):
    rng = random.Random(seed)
    # GPU widths: mostly single-GPU, a meaningful minority of gang jobs.
    # Width is capped at the host's GPU count so the trace is replayable anywhere.
    widths, wweights = [1], [0.70]
    if n_gpus >= 2:
        widths.append(2)
        wweights.append(0.30)
    if n_gpus >= 4:
        widths.append(4)
        wweights = [0.60, 0.25, 0.15]

    jobs, t = [], 0.0
    for i in range(n_jobs):
        # Poisson process -> exponential inter-arrival gaps.
        t += rng.expovariate(rate)
        jobs.append({
            "id": f"j{i:03d}",
            "arrival_s": round(t, 3),
            "gpus": rng.choices(widths, weights=wweights, k=1)[0],
            "burn_s": rng.randint(burn_lo, burn_hi),
            # 0 = normal, 1 = high. Drives RQ4 (preemption) on both stacks.
            "priority": 1 if rng.random() < 0.20 else 0,
        })
    return jobs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=60)
    ap.add_argument("--gpus", type=int, default=2, help="GPUs on the test host")
    ap.add_argument("--rate", type=float, default=0.25,
                    help="arrivals per second (mean gap = 1/rate)")
    ap.add_argument("--seed", type=int, default=20260723)
    ap.add_argument("--burn-lo", type=int, default=20)
    ap.add_argument("--burn-hi", type=int, default=60)
    ap.add_argument("-o", "--out", default="trace.json")
    a = ap.parse_args()

    jobs = gen(a.jobs, a.gpus, a.rate, a.seed, a.burn_lo, a.burn_hi)
    meta = {
        "seed": a.seed, "rate_per_s": a.rate, "host_gpus": a.gpus,
        "n_jobs": len(jobs), "span_s": jobs[-1]["arrival_s"],
        "gpu_seconds": sum(j["gpus"] * j["burn_s"] for j in jobs),
        "offered_load": sum(j["gpus"] * j["burn_s"] for j in jobs)
                        / (jobs[-1]["arrival_s"] * a.gpus),
    }
    with open(a.out, "w") as f:
        json.dump({"meta": meta, "jobs": jobs}, f, indent=1)
    print(json.dumps(meta, indent=2))
    print(f"wrote {a.out}")


def _selfcheck():
    """Same seed -> same trace; load is in a sane range; widths respect host GPUs."""
    a = gen(60, 2, 0.25, 7, 20, 60)
    b = gen(60, 2, 0.25, 7, 20, 60)
    assert a == b, "trace is not reproducible under a fixed seed"
    assert gen(60, 4, 0.25, 7, 20, 60) != a, "GPU count must change the width mix"
    assert all(j["gpus"] <= 2 for j in a), "width exceeded host GPU count"
    assert all(j["burn_s"] >= 20 for j in a)
    arr = [j["arrival_s"] for j in a]
    assert arr == sorted(arr), "arrivals must be monotonic"
    load = sum(j["gpus"] * j["burn_s"] for j in a) / (arr[-1] * 2)
    assert 1.0 < load < 20.0, f"trace should oversubscribe the host, got {load:.2f}"
    print("selfcheck ok; offered load =", round(load, 2))


if __name__ == "__main__":
    import sys
    if "--selfcheck" in sys.argv:
        _selfcheck()
    else:
        main()
